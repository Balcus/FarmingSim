    private static GameObject LoadFallbackPrefab(string fileName)
    {
        return AssetDatabase.LoadAssetAtPath<GameObject>(AutoPrefabsFolder + "/" + fileName);
    }

    private static void CreatePrimitivePrefab(string name, PrimitiveType type, Material mat, Vector3 scale)
    {
        string path = AutoPrefabsFolder + "/" + name + ".prefab";
        if (AssetDatabase.LoadAssetAtPath<GameObject>(path) != null) return;

        var go = GameObject.CreatePrimitive(type);
        go.name = name;
        go.transform.localScale = scale;
        var renderer = go.GetComponent<Renderer>();
        if (renderer != null) renderer.sharedMaterial = mat;
        var collider = go.GetComponent<Collider>();
        if (collider != null) UnityEngine.Object.DestroyImmediate(collider);
        PrefabUtility.SaveAsPrefabAsset(go, path);
        UnityEngine.Object.DestroyImmediate(go);
    }
